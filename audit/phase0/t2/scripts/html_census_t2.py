"""Read-only HTML classification: reads the first 4 KiB of every .html/.htm file and classifies by generator markers."""
import csv, os, re, json, collections
ROOT = r"D:\MBI-BRAIN"; B = r"D:\AgenticAI\second-brain-rag\audit\phase0\t2"
RULES = [("javadoc", rb"Generated by javadoc|<!-- Generated by javadoc|javadoc"), ("doxygen", rb"Generated by Doxygen|doxygen"),
         ("man_page_html", rb"man2html|man-pages|Linux Programmer's Manual|<title>[a-z_0-9.]+\(\d\)"), ("saved_web_page", rb"saved from url="),
         ("sphinx", rb"Sphinx"), ("office_export", rb"urn:schemas-microsoft-com:office|Microsoft Word|ProgId"),
         ("matlab_publish", rb"MATLAB|mathworks"), ("eclipse_help", rb"Eclipse|org\.eclipse"), ("frameset_index", rb"<frameset")]
rows = [r for r in csv.DictReader(open(B + r"\inventory_t2.csv", encoding="utf-8")) if r["ext"] in (".html", ".htm")]
out = open(B + r"\html_census_t2.jsonl", "w", encoding="utf-8")
for r in rows:
    d = {"relpath": r["relpath"], "size": int(r["size"])}
    try:
        head = open(os.path.join(ROOT, r["relpath"]), "rb").read(4096)
        d["class"] = next((k for k, pat in RULES if re.search(pat, head, re.I)), "other")
        m = re.search(rb"<title>(.*?)</title>", head, re.I | re.S); d["title"] = m.group(1)[:80].decode("utf-8", "replace").strip() if m else None
    except OSError as e: d["error"] = str(e)[:100]
    out.write(json.dumps(d, ensure_ascii=False) + "\n")
out.close(); print("html files", len(rows))
